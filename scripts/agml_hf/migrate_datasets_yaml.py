"""
Stage 0 (prep) — Regenerate src/config/datasets.yaml from the Project-AgML HF
catalog (scripts/agml_hf/catalog_datasets.py output), carrying forward
crop/task_type/location/class_overrides for datasets that already existed under
the old `agml` pip package, and flagging brand-new datasets for manual review.

Classification-only: dataset_type == "classification" entries from the catalog
are the only ones written to the output YAML. As of catalog_datasets.py's
output split, --catalog (src/config/hf_catalog.json) should already contain
classification entries exclusively — detection/segmentation/multimodal
datasets are routed to src/config/hf_catalog_excluded.json at the catalog
stage, not here. The dataset_type filter below is kept as a defensive
no-op in case that invariant is ever violated (e.g. a hand-edited catalog
file), not the primary exclusion mechanism anymore.

Writes to --output (default: a `.new` file, NOT the original) plus a markdown
review report. Inspect the diff and the report, resolve every flagged item, and
only then copy the `.new` file over the original.

Usage:
  uv run python scripts/agml_hf/migrate_datasets_yaml.py \
    --catalog src/config/hf_catalog.json \
    --current src/config/datasets.yaml \
    --output  src/config/datasets.yaml.new \
    --review_report outputs/migration/datasets_migration_review.md
"""

from __future__ import annotations

import argparse
import json
import sys
from difflib import get_close_matches
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from src.common.dataset_config import DatasetConfig, clean_class_list, load_datasets  # noqa: E402

HEADER = """\
# AgML image classification datasets, sourced from https://huggingface.co/Project-AgML.
# Regenerated by scripts/agml_hf/migrate_datasets_yaml.py — see
# outputs/migration/datasets_migration_review.md for the review log of this run.
#
# task_type options:
#   disease            - leaf/plant disease classification
#   pest_damage        - insect/pest classification or physical/abiotic damage
#   weed_identification - weed or mixed crop/weed species classification
#   crop_identification - crop ripeness or growth-stage classification
#
# skip: true          - exclude dataset entirely from generation
# hf_config            - which HF dataset config/split-group to load (e.g. "raw" vs "augmented")
#
# Q3/Q4 (description questions) are only generated for
# task_type: disease | pest_damage.
# Datasets with task_type: weed_identification | crop_identification
# get Q1/Q2 only.
"""


def normalize_label(s: str) -> str:
    return "".join(c for c in s.lower().replace("_", " ").replace("-", " ") if c.isalnum() or c == " ").strip()


def fuzzy_match(old_label: str, candidates: list[str]) -> str | None:
    norm_candidates = {normalize_label(c): c for c in candidates}
    norm_old = normalize_label(old_label)
    if norm_old in norm_candidates:
        return norm_candidates[norm_old]
    close = get_close_matches(norm_old, list(norm_candidates.keys()), n=1, cutoff=0.8)
    return norm_candidates[close[0]] if close else None


def build_entry(name: str, meta: dict, old: DatasetConfig | None) -> dict:
    cfg = meta["configs"][meta["preferred_config"]]
    hf_classes = cfg["class_names"] or []
    n_images = sum(cfg["splits"].values())

    if old is not None:
        entry = {
            "agml_name": name,
            "crop": old.crop,
            "task_type": old.task_type,
            "n_images": n_images,
            "classes": hf_classes,
            "hf_config": meta["preferred_config"],
            "location": old.location,
            "skip": old.skip,
            "skip_description": old.skip_description,
            "notes": old.notes,
        }
        if old.class_overrides:
            hf_classes_clean = clean_class_list(hf_classes)
            remapped, unmatched = {}, []
            for old_label, override_type in old.class_overrides.items():
                match_clean = fuzzy_match(old_label, hf_classes_clean)
                if match_clean is None:
                    unmatched.append(old_label)
                    continue
                # map back from cleaned label to the raw HF label string
                raw_match = hf_classes[hf_classes_clean.index(match_clean)]
                remapped[raw_match] = override_type
            if remapped:
                entry["class_overrides"] = remapped
            entry["_unmatched_overrides"] = unmatched  # consumed by caller, stripped before writing
        return entry

    return {
        "agml_name": name,
        "crop": None,
        "task_type": None,
        "n_images": n_images,
        "classes": hf_classes,
        "hf_config": meta["preferred_config"],
        "location": [],
        "skip": True,
        "notes": "NEW - auto-added by migrate_datasets_yaml.py, needs crop/task_type/location review",
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="src/config/hf_catalog.json")
    ap.add_argument("--current", default="src/config/datasets.yaml")
    ap.add_argument("--output", default="src/config/datasets.yaml.new")
    ap.add_argument("--review_report", default="outputs/migration/datasets_migration_review.md")
    args = ap.parse_args()

    catalog: dict = json.loads(Path(args.catalog).read_text())
    current = load_datasets(Path(args.current))
    current_by_name = {d.agml_name: d for d in current}

    classification = {n: m for n, m in catalog.items() if m.get("dataset_type") == "classification"}
    non_classification = {n: m for n, m in catalog.items() if m.get("dataset_type") != "classification" and "error" not in m}
    errored = {n: m for n, m in catalog.items() if "error" in m}

    flags = {
        "label_text_changed": [],
        "new_dataset_needs_classification": [],
        "missing_from_hf": [],
        "excluded_non_classification": sorted(non_classification.keys()),
        "catalog_errors": [(n, m["error"]) for n, m in errored.items()],
    }

    entries = []
    for name, meta in sorted(classification.items()):
        old = current_by_name.get(name)
        entry = build_entry(name, meta, old)
        unmatched = entry.pop("_unmatched_overrides", [])
        if unmatched:
            flags["label_text_changed"].append((name, unmatched))
        if old is not None:
            old_clean = set(old.clean_classes)
            new_clean = set(clean_class_list(entry["classes"]))
            if old_clean != new_clean:
                flags["label_text_changed"].append(
                    (name, f"class set changed: -{old_clean - new_clean} +{new_clean - old_clean}")
                )
        else:
            flags["new_dataset_needs_classification"].append(name)
        entries.append(entry)

    for name in current_by_name:
        if name not in catalog:
            flags["missing_from_hf"].append(name)
            old = current_by_name[name]
            entries.append({
                "agml_name": old.agml_name,
                "crop": old.crop,
                "task_type": old.task_type,
                "n_images": old.n_images,
                "classes": old.classes,
                "location": old.location,
                "skip": old.skip,
                "skip_description": old.skip_description,
                "notes": (old.notes + " | " if old.notes else "")
                         + "NOT FOUND on Project-AgML HF org as of this migration run - kept as-is, source unresolved",
                **({"class_overrides": old.class_overrides} if old.class_overrides else {}),
            })

    entries.sort(key=lambda e: (e["skip"], e["agml_name"]))

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write(HEADER + "\ndatasets:\n\n")
        for e in entries:
            block = yaml.safe_dump([e], default_flow_style=False, sort_keys=False, allow_unicode=True)
            block = "\n".join("  " + line if line.strip() else line for line in block.splitlines())
            f.write(block + "\n\n")

    report_path = Path(args.review_report)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    with open(report_path, "w") as f:
        f.write("# datasets.yaml migration review\n\n")
        f.write(f"Catalog: {len(catalog)} total | "
                f"{len(classification)} classification | "
                f"{len(non_classification)} excluded (non-classification) | "
                f"{len(errored)} catalog errors\n\n")
        f.write(f"Output entries written: {len(entries)}\n\n")

        f.write(f"## New datasets needing crop/task_type/location review ({len(flags['new_dataset_needs_classification'])})\n\n")
        for n in flags["new_dataset_needs_classification"]:
            f.write(f"- [ ] `{n}` — https://huggingface.co/Project-AgML/{n}\n")

        f.write(f"\n## class_overrides / class-set changes needing re-check ({len(flags['label_text_changed'])})\n\n")
        for n, detail in flags["label_text_changed"]:
            f.write(f"- [ ] `{n}` — {detail}\n")

        f.write(f"\n## In current datasets.yaml but missing from Project-AgML HF org ({len(flags['missing_from_hf'])})\n\n")
        for n in flags["missing_from_hf"]:
            f.write(f"- [ ] `{n}` — kept as-is in output, decide: drop, or keep sourcing via pip `agml`\n")

        f.write(f"\n## Excluded: non-classification datasets in the org ({len(flags['excluded_non_classification'])})\n\n")
        f.write("Not written to datasets.yaml — detection/segmentation/multimodal, out of scope "
                "for this pipeline. Each entry's type is shown below.\n\n")
        for n in flags["excluded_non_classification"]:
            f.write(f"- `{n}` ({non_classification[n]['dataset_type']})\n")

        if flags["catalog_errors"]:
            f.write(f"\n## Catalog introspection errors ({len(flags['catalog_errors'])})\n\n")
            for n, err in flags["catalog_errors"]:
                f.write(f"- `{n}`: {err}\n")

    print(f"Wrote {len(entries)} entries -> {out_path}")
    print(f"Review report -> {report_path}")
    print(f"  new datasets needing review: {len(flags['new_dataset_needs_classification'])}")
    print(f"  overrides/classes needing re-check: {len(flags['label_text_changed'])}")
    print(f"  missing from HF: {len(flags['missing_from_hf'])}")
    print(f"  excluded non-classification: {len(flags['excluded_non_classification'])}")


if __name__ == "__main__":
    main()
