"""
Stage 5 (prep) — Regenerate src/config/detection_datasets.yaml from
catalog_detection_datasets.py's output.

**Merge-safe since 2026-10 (was a full-overwrite-every-run script before
— fixed the moment a real re-catalog run was about to need it, not
preemptively)**: if --output already exists, this now reads it FIRST
and carries forward two kinds of prior manual edit before writing the
fresh file, rather than silently discarding them:
  1. **`crop`** — hand-filled after a prior run (this script itself
     always derives a fresh entry's crop as null; nothing re-derives it
     from the catalog). Any existing entry with a non-null `crop` keeps
     it, for every dataset, not just held-out ones.
  2. **Deliberate `skip: true` holdouts** — e.g.
     scripts/download_heldout_detection.py's 5 Paper 2 Stage 4 datasets,
     identified by their own `notes` field starting with the literal
     "HELD OUT for Paper 2 Stage 4" marker (not just any skip: true —
     an UNRESOLVED-class skip is still meant to flip to false once
     resolved, so only the deliberately-marked ones are protected).
     Both `skip` and `notes` are carried forward unconditionally for
     these, regardless of what the fresh catalog run would have
     derived — a dataset whose class_names become resolvable after a
     re-catalog does NOT get silently un-held-out.
A brand-new dataset name (not in the prior file at all) gets the
ordinary fresh derivation — class_names resolved -> skip: false,
unresolved -> skip: true + the standard "needs manual review" notes —
exactly as before this fix; only EXISTING entries are protected.

task_type is a constant "object_detection" for every entry (unlike
classification's disease/pest_damage/species_identification/
quality_identification split) — there's no equivalent task-type taxonomy
for detection yet; downstream scripts (detection_baseline.py,
detection_verifier.py) don't currently branch on it, so one value is
sufficient until/unless that changes.

Usage:
  uv run python main.py migrate-detection-datasets \\
    --catalog src/config/hf_detection_catalog.json \\
    --output  src/config/detection_datasets.yaml
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

_HELD_OUT_MARKER = "HELD OUT for Paper 2 Stage 4"

HEADER = """\
# AgML object-detection datasets, sourced from https://huggingface.co/Project-AgML.
# Regenerated by scripts/agml_hf/migrate_detection_datasets_yaml.py from
# src/config/hf_detection_catalog.json (catalog_detection_datasets.py's output).
# MERGE-SAFE: re-running this preserves any existing entry's hand-filled
# `crop` and any deliberate (notes-marked) `skip: true` holdout — see this
# script's own module docstring. Only brand-new dataset names get fresh
# auto-derived values.
#
# task_type is a constant "object_detection" for every entry — see this
# script's module docstring for why.
#
# skip: true means EITHER class_names could not be resolved for this
# dataset (see `notes`) — review manually (the dataset's own README/
# dataset card on the HF Hub is usually the fastest way to find the real
# class list) and flip to false once resolved — OR it's a deliberate
# held-out dataset (notes starts with "HELD OUT for Paper 2 Stage 4") —
# never flip those, see docs/stage4_detection_context_memory.md.
#
# bbox_convention is MEASURED (catalog_detection_datasets.py samples real
# rows), not assumed — {"scale": "pixel"|"normalized", "format":
# "xyxy"|"xywh", ...}. Confirm visually via `main.py detection-qc-plot`
# before trusting it on any dataset you actually use.
"""


def build_entry(name: str, meta: dict) -> dict:
    class_names = meta.get("class_names")
    cfg = meta.get("configs", {}).get(meta.get("preferred_config", "default"), {})
    n_images = sum(cfg.get("splits", {}).values()) if cfg.get("splits") else 0
    bbox_convention = meta.get("bbox_convention") or {}

    entry = {
        "agml_name": name,
        "crop": None,
        "task_type": "object_detection",
        "n_images": n_images,
        "classes": class_names or [],
        "hf_config": meta.get("preferred_config", "default"),
        "location": [],
        "skip": class_names is None,
        "bbox_convention": bbox_convention,
        "notes": "" if class_names else (
            "class_names UNRESOLVED by catalog_detection_datasets.py (checked HF Features, "
            "dataset card, and a sample row) — needs manual class-list lookup before use."
        ),
    }
    return entry


def load_existing_entries(output_path: Path) -> dict[str, dict]:
    """{agml_name: entry} from an existing --output file, or {} if none
    exists yet (first-ever run, nothing to merge forward)."""
    if not output_path.exists():
        return {}
    existing = yaml.safe_load(output_path.read_text()) or {}
    return {e["agml_name"]: e for e in existing.get("datasets", [])}


def merge_forward(fresh: dict, old: dict | None) -> dict:
    """fresh entry, with crop/deliberate-holdout fields carried forward
    from `old` (the same dataset's entry in the file being overwritten)
    when present — see module docstring for exactly which fields and
    why. `old=None` (brand-new dataset) returns `fresh` unchanged."""
    if old is None:
        return fresh
    merged = dict(fresh)
    if old.get("crop") is not None:
        merged["crop"] = old["crop"]
    if old.get("skip") and str(old.get("notes", "")).startswith(_HELD_OUT_MARKER):
        merged["skip"] = True
        merged["notes"] = old["notes"]
    return merged


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--catalog", default="src/config/hf_detection_catalog.json")
    ap.add_argument("--output", default="src/config/detection_datasets.yaml")
    args = ap.parse_args()

    catalog: dict = json.loads(Path(args.catalog).read_text())
    out_path = Path(args.output)
    old_by_name = load_existing_entries(out_path)

    entries = []
    n_crop_preserved = n_holdout_preserved = n_new = 0
    for name, meta in sorted(catalog.items()):
        fresh = build_entry(name, meta)
        old = old_by_name.get(name)
        merged = merge_forward(fresh, old)
        if old is None:
            n_new += 1
        else:
            if old.get("crop") is not None:
                n_crop_preserved += 1
            if merged["skip"] and merged is not fresh and merged.get("notes") == old.get("notes") and old.get("skip"):
                n_holdout_preserved += 1
        entries.append(merged)
    entries.sort(key=lambda e: (e["skip"], e["agml_name"]))

    n_resolved = sum(1 for e in entries if not e["skip"])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write(HEADER + "\ndatasets:\n\n")
        for e in entries:
            block = yaml.safe_dump([e], default_flow_style=False, sort_keys=False, allow_unicode=True)
            block = "\n".join("  " + line if line.strip() else line for line in block.splitlines())
            f.write(block + "\n\n")

    print(f"Wrote {len(entries)} entries -> {out_path}")
    print(f"  {n_resolved} usable (skip: false), {len(entries) - n_resolved} need manual class-list review (skip: true)")
    print(f"  {n_new} brand-new dataset(s) not in the prior file")
    print(f"  {n_crop_preserved} existing crop label(s) carried forward")
    print(f"  {n_holdout_preserved} deliberate held-out skip(s) (notes-marked) carried forward")


if __name__ == "__main__":
    main()
