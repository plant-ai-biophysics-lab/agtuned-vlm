"""
AgML Inference: Visual VQA Evaluation
======================================
Evaluates a VLM on the two tasks generated by agml_scraper.py:

  Dataset A (description): image + visual description question
    Metric: ROUGE-1, ROUGE-2, ROUGE-L vs synthesized ground-truth description

  Dataset B (classification): image + visual classification question
    Metric: Accuracy, F1-macro, F1-weighted vs class label

Images are loaded from AgML using agml_dataset + image_names stored in JSONL metadata.
Only datasets with skip: false in datasets.yaml are evaluated.

Usage:
    uv run python agml_inference.py --model Qwen/Qwen3.6-35B-A3B
    uv run python agml_inference.py --model google/gemma-4-E2B-it --n_samples 3
    uv run python agml_inference.py --descriptions_jsonl outputs/agml_descriptions.jsonl
"""

import argparse
import csv
import json
import re
import time
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import yaml
from PIL import Image as PILImage
from rouge_score import rouge_scorer as rs_scorer
from sklearn.metrics import accuracy_score, classification_report, f1_score
from vllm import LLM, SamplingParams

# ── Sampling params ────────────────────────────────────────────────────────────

DESC_PARAMS = SamplingParams(temperature=0.0, max_tokens=256, repetition_penalty=1.1)

# Short answer — stop at newline or punctuation after the class name
CLS_PARAMS = SamplingParams(
    temperature=0.0, max_tokens=32, repetition_penalty=1.1,
    stop=["\n", ".", ",", ";"],
)

# Appended to every classification question to constrain the response
CLS_SUFFIX = " Respond with only the class name, nothing else."

_REPEAT_RE = re.compile(r'(\b\w+\b)(\s+\1){4,}', re.IGNORECASE)
_THINK_RE  = re.compile(r'<think>.*?</think>', re.DOTALL | re.IGNORECASE)


# ── Response cleaning (adapted from text_qa.py) ───────────────────────────────

def _clean_response(text: str) -> str:
    text = _THINK_RE.sub('', text).strip()
    think_start = text.lower().find('<think>')
    if think_start != -1:
        text = text[:think_start].strip()
    m = _REPEAT_RE.search(text)
    if m:
        text = text[:m.start()].strip()
    return text


def _apply_chat_template(tokenizer, prompt: str) -> str:
    messages = [{"role": "user", "content": prompt}]
    try:
        return tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True, enable_thinking=False
        )
    except TypeError:
        pass
    try:
        return tokenizer.apply_chat_template(
            [{"role": "system", "content": "/no_think"}, *messages],
            tokenize=False, add_generation_prompt=True,
        )
    except Exception:
        return tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )


# ── Data loading ───────────────────────────────────────────────────────────────

def load_datasets_config(config_path: Path) -> dict[str, dict]:
    with open(config_path) as f:
        cfg = yaml.safe_load(f)
    return {d["agml_name"]: d for d in cfg["datasets"] if not d.get("skip", False)}


def load_description_records(jsonl_path: Path, active_datasets: set[str]) -> list[dict]:
    records = []
    with open(jsonl_path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r.get("metadata", {}).get("agml_dataset") in active_datasets:
                records.append(r)
    print(f"  {len(records)} records from {jsonl_path.name}")
    return records


def build_name_map(agml_name: str) -> dict[str, str]:
    """Returns {filename: full_path} for all images in an AgML dataset."""
    import agml
    loader   = agml.data.AgMLDataLoader(agml_name)
    contents = loader.export_contents()
    return {Path(str(p)).name: str(p) for p in contents.keys()}


def clean_class_list(raw_classes: list[str]) -> list[str]:
    """Apply same label cleaning as agml_scraper.parse_class_label."""
    cleaned = []
    for c in raw_classes:
        if "___" in c:
            cleaned.append(c.split("___", 1)[1].replace("_", " ").strip())
        else:
            cleaned.append(c.replace("_", " ").strip())
    return cleaned


def resolve_class(response: str, classes: list[str]) -> str | None:
    """Case-insensitive exact match, then single-match substring fallback."""
    resp = response.lower().strip()
    for cls in classes:
        if cls.lower() == resp:
            return cls
    matches = [cls for cls in classes if cls.lower() in resp]
    return matches[0] if len(matches) == 1 else None


# ── Prompt building ────────────────────────────────────────────────────────────

def build_multimodal_prompt(tokenizer, image: PILImage.Image, question: str) -> dict:
    messages = [
        {
            "role": "user",
            "content": [{"type": "image"}, {"type": "text", "text": question}],
        }
    ]
    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    return {"prompt": text, "multi_modal_data": {"image": image}}


# ── Inference ──────────────────────────────────────────────────────────────────

def load_llm(model_id: str) -> tuple[LLM, object]:
    llm = LLM(
        model=model_id,
        dtype="bfloat16",
        max_model_len=16384,
        gpu_memory_utilization=0.9,
        max_num_seqs=64,
        limit_mm_per_prompt={"image": 1},
    )
    return llm, llm.get_tokenizer()


def run_batch(
    llm: LLM,
    tokenizer,
    images: list[PILImage.Image],
    question: str,
    params: SamplingParams,
) -> list[str]:
    prompts = [build_multimodal_prompt(tokenizer, img, question) for img in images]
    outputs = llm.generate(prompts, sampling_params=params)
    return [_clean_response(o.outputs[0].text) for o in outputs]


# ── Metrics ────────────────────────────────────────────────────────────────────

def rouge_scores(prediction: str, reference: str) -> dict[str, float]:
    scorer = rs_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True)
    s = scorer.score(reference, prediction)
    return {
        "rouge1": round(s["rouge1"].fmeasure, 4),
        "rouge2": round(s["rouge2"].fmeasure, 4),
        "rougeL": round(s["rougeL"].fmeasure, 4),
    }


def dataset_rouge_summary(rows: list[dict]) -> dict:
    return {
        "rouge1":   round(np.mean([r["rouge1"] for r in rows]), 4),
        "rouge2":   round(np.mean([r["rouge2"] for r in rows]), 4),
        "rougeL":   round(np.mean([r["rougeL"] for r in rows]), 4),
        "n_images": len(rows),
    }


def dataset_cls_summary(rows: list[dict]) -> dict:
    resolvable = [r for r in rows if r["resolvable"]]
    if not resolvable:
        return {"accuracy": 0.0, "f1_macro": 0.0, "f1_weighted": 0.0,
                "n_images": len(rows), "n_resolvable": 0}
    refs   = [r["class_label"]    for r in resolvable]
    preds  = [r["resolved_class"] for r in resolvable]
    labels = sorted(set(refs) | set(preds))
    return {
        "accuracy":     round(accuracy_score(refs, preds), 4),
        "f1_macro":     round(f1_score(refs, preds, average="macro",
                                       labels=labels, zero_division=0), 4),
        "f1_weighted":  round(f1_score(refs, preds, average="weighted",
                                       labels=labels, zero_division=0), 4),
        "n_images":     len(rows),
        "n_resolvable": len(resolvable),
    }


def naive_cls_summary(rows: list[dict]) -> dict:
    """Shuffle ground truth labels within dataset — chance-level floor."""
    resolvable = [r for r in rows if r["resolvable"]]
    if not resolvable:
        return {"accuracy": 0.0, "f1_macro": 0.0, "f1_weighted": 0.0,
                "n_images": len(rows), "n_resolvable": 0}
    refs     = [r["class_label"] for r in resolvable]
    shuffled = refs.copy()
    rng      = np.random.default_rng(42)
    rng.shuffle(shuffled)
    labels   = sorted(set(refs))
    return {
        "accuracy":     round(accuracy_score(refs, shuffled), 4),
        "f1_macro":     round(f1_score(refs, shuffled, average="macro",
                                       labels=labels, zero_division=0), 4),
        "f1_weighted":  round(f1_score(refs, shuffled, average="weighted",
                                       labels=labels, zero_division=0), 4),
        "n_images":     len(rows),
        "n_resolvable": len(resolvable),
    }


# ── Plots ──────────────────────────────────────────────────────────────────────

def plot_rouge_by_dataset(results_a: dict, output_dir: Path) -> None:
    datasets = [k for k in results_a if k != "overall"]
    if not datasets:
        return
    metrics = ["rouge1", "rouge2", "rougeL"]
    x = np.arange(len(datasets))
    width = 0.25

    fig, ax = plt.subplots(figsize=(max(8, len(datasets) * 0.6), 5))
    for i, m in enumerate(metrics):
        vals = [results_a[ds][m] for ds in datasets]
        ax.bar(x + i * width, vals, width, label=m.upper())

    ax.set_xticks(x + width)
    ax.set_xticklabels([d.replace("_classification", "").replace("_", " ")
                        for d in datasets], rotation=45, ha="right", fontsize=7)
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Score")
    ax.set_title("Dataset A — ROUGE by Dataset")
    ax.legend()
    plt.tight_layout()
    path = output_dir / "rouge_by_dataset.png"
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {path}")


def plot_cls_by_dataset(results_b: dict, results_b_naive: dict, output_dir: Path) -> None:
    datasets = list(results_b.keys())
    if not datasets:
        return
    metrics = ["accuracy", "f1_macro", "f1_weighted"]
    x     = np.arange(len(datasets))
    width = 0.18

    fig, ax = plt.subplots(figsize=(max(8, len(datasets) * 0.8), 5))
    colors = ["#2196F3", "#4CAF50", "#FF9800"]
    for i, (m, color) in enumerate(zip(metrics, colors)):
        model_vals = [results_b[ds][m] for ds in datasets]
        naive_vals = [results_b_naive.get(ds, {}).get(m, 0) for ds in datasets]
        offset = (i * 2) * width - (len(metrics) - 1) * width
        ax.bar(x + offset,         model_vals, width, label=m.replace("_", " ").title(),
               color=color, alpha=0.85)
        ax.bar(x + offset + width, naive_vals, width, label=f"{m.replace('_', ' ').title()} (naive)",
               color=color, alpha=0.35, hatch="///", edgecolor=color)

    ax.set_xticks(x)
    ax.set_xticklabels([d.replace("_classification", "").replace("_", " ")
                        for d in datasets], rotation=45, ha="right", fontsize=7)
    ax.set_ylim(0, 1.15)
    ax.set_ylabel("Score")
    ax.set_title("Dataset B — Classification Metrics by Dataset (solid=model, hatched=naive)")
    ax.legend(fontsize=7, ncol=2)
    plt.tight_layout()
    path = output_dir / "classification_by_dataset.png"
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {path}")


# ── Main ───────────────────────────────────────────────────────────────────────

def main(args: argparse.Namespace) -> None:
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    datasets_cfg    = load_datasets_config(Path(args.datasets_config))
    active_datasets = set(datasets_cfg.keys())
    records         = load_description_records(
        Path(args.descriptions_jsonl), active_datasets
    )

    print(f"\nModel:   {args.model}")
    print(f"Records: {len(records)}  |  Datasets: {len(active_datasets)}")
    llm, tokenizer = load_llm(args.model)

    desc_rows: list[dict] = []
    cls_rows:  list[dict] = []
    agml_cache: dict[str, dict[str, str]] = {}  # agml_name → {filename: path}

    t_start = time.perf_counter()

    for record in records:
        meta          = record["metadata"]
        agml_name     = meta["agml_dataset"]
        class_label   = meta["class_label"]
        task_type     = meta["task_type"]
        crop          = meta["crop"]
        image_names   = meta["image_names"]
        synth_desc    = record["messages"][1]["content"]
        visual_desc_q = meta["visual_question"]
        visual_cls_q  = meta.get("visual_cls_question")

        if args.n_samples:
            image_names = image_names[:args.n_samples]

        # Build AgML filename→path map (cached per dataset)
        if agml_name not in agml_cache:
            print(f"\n  Building image map: {agml_name}...")
            agml_cache[agml_name] = build_name_map(agml_name)
        name_map = agml_cache[agml_name]

        images, valid_names = [], []
        for name in image_names:
            if name in name_map:
                images.append(PILImage.open(name_map[name]).convert("RGB"))
                valid_names.append(name)
            else:
                print(f"    [warn] {name} not in {agml_name}")
        if not images:
            continue

        print(f"  {agml_name} / {class_label}  ({len(images)} images)")

        # ── Dataset A: visual description ─────────────────────────────────
        desc_preds = run_batch(llm, tokenizer, images, visual_desc_q, DESC_PARAMS)
        for pred, img_name in zip(desc_preds, valid_names):
            scores = rouge_scores(pred, synth_desc)
            desc_rows.append({
                "agml_dataset": agml_name,
                "class_label":  class_label,
                "task_type":    task_type,
                "crop":         crop,
                "image_name":   img_name,
                "prediction":   pred,
                "ground_truth": synth_desc,
                **scores,
            })

        # ── Dataset B: visual classification ──────────────────────────────
        if visual_cls_q:
            raw_classes   = datasets_cfg[agml_name].get("classes", [])
            clean_classes = clean_class_list(raw_classes)
            cls_question  = visual_cls_q + CLS_SUFFIX

            cls_preds = run_batch(llm, tokenizer, images, cls_question, CLS_PARAMS)
            for pred, img_name in zip(cls_preds, valid_names):
                resolved = resolve_class(pred, clean_classes)
                correct  = (resolved is not None and
                            resolved.lower() == class_label.lower())
                cls_rows.append({
                    "agml_dataset":   agml_name,
                    "class_label":    class_label,
                    "task_type":      task_type,
                    "crop":           crop,
                    "image_name":     img_name,
                    "raw_prediction": pred,
                    "resolved_class": resolved or "",
                    "correct":        int(correct),
                    "resolvable":     int(resolved is not None),
                })

    elapsed = time.perf_counter() - t_start

    # ── Save per-image CSVs ────────────────────────────────────────────────────
    if desc_rows:
        desc_csv = output_dir / "agml_inference_descriptions.csv"
        with open(desc_csv, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(desc_rows[0].keys()))
            writer.writeheader()
            writer.writerows(desc_rows)
        print(f"\nSaved: {desc_csv}")

    if cls_rows:
        cls_csv = output_dir / "agml_inference_classification.csv"
        with open(cls_csv, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(cls_rows[0].keys()))
            writer.writeheader()
            writer.writerows(cls_rows)
        print(f"Saved: {cls_csv}")

    # ── Aggregate metrics ──────────────────────────────────────────────────────
    by_ds_desc: dict[str, list] = defaultdict(list)
    for row in desc_rows:
        by_ds_desc[row["agml_dataset"]].append(row)

    by_ds_cls: dict[str, list] = defaultdict(list)
    for row in cls_rows:
        by_ds_cls[row["agml_dataset"]].append(row)

    results_a = {ds: dataset_rouge_summary(rows) for ds, rows in by_ds_desc.items()}
    if desc_rows:
        results_a["overall"] = dataset_rouge_summary(desc_rows)

    results_b = {ds: dataset_cls_summary(rows) for ds, rows in by_ds_cls.items()}
    results_b_naive = {ds: naive_cls_summary(rows) for ds, rows in by_ds_cls.items()}

    # Overall naive across all datasets
    if cls_rows:
        all_resolvable = [r for r in cls_rows if r["resolvable"]]
        if all_resolvable:
            refs     = [r["class_label"] for r in all_resolvable]
            shuffled = refs.copy()
            np.random.default_rng(42).shuffle(shuffled)
            label_set = sorted(set(refs))
            results_b_naive["overall"] = {
                "accuracy":     round(accuracy_score(refs, shuffled), 4),
                "f1_macro":     round(f1_score(refs, shuffled, average="macro",
                                               labels=label_set, zero_division=0), 4),
                "f1_weighted":  round(f1_score(refs, shuffled, average="weighted",
                                               labels=label_set, zero_division=0), 4),
                "n_images":     len(all_resolvable),
                "n_resolvable": len(all_resolvable),
            }

    results = {
        "model":          args.model,
        "total_time_s":   round(elapsed, 3),
        "n_classes":      len(records),
        "dataset_a":      results_a,
        "dataset_b":      results_b,
        "dataset_b_naive": results_b_naive,
    }
    metrics_path = output_dir / "agml_inference_metrics.json"
    with open(metrics_path, "w") as f:
        json.dump(results, f, indent=2)
    print(f"Saved: {metrics_path}")

    # ── Summary ────────────────────────────────────────────────────────────────
    if results_a:
        ov = results_a.get("overall", {})
        print(f"\n=== Dataset A — Visual Description ===")
        print(f"  Overall  ROUGE-1={ov.get('rouge1', 0):.3f}  "
              f"ROUGE-2={ov.get('rouge2', 0):.3f}  "
              f"ROUGE-L={ov.get('rougeL', 0):.3f}  "
              f"({ov.get('n_images', 0)} images)")

    if results_b:
        print(f"\n=== Dataset B — Visual Classification ===")
        header = f"  {'Dataset':<45} {'Acc':>6} {'F1-mac':>8} {'F1-wt':>7} {'Naive Acc':>10} {'Naive F1':>9} {'Res/Tot':>10}"
        print(header)
        print(f"  {'-' * len(header)}")
        for ds, m in results_b.items():
            naive = results_b_naive.get(ds, {})
            print(f"  {ds:<45} {m['accuracy']:>6.3f} {m['f1_macro']:>8.3f} "
                  f"{m['f1_weighted']:>7.3f} "
                  f"{naive.get('accuracy', 0):>10.3f} {naive.get('f1_macro', 0):>9.3f} "
                  f"{m['n_resolvable']:>4}/{m['n_images']:<4}")
        if "overall" in results_b_naive:
            nv = results_b_naive["overall"]
            print(f"\n  Naive overall  Acc={nv['accuracy']:.3f}  "
                  f"F1-macro={nv['f1_macro']:.3f}  F1-weighted={nv['f1_weighted']:.3f}")

    print(f"\nTotal time: {elapsed:.1f}s")

    # ── Plots ──────────────────────────────────────────────────────────────────
    print("\nGenerating plots...")
    plot_rouge_by_dataset(results_a, output_dir)
    plot_cls_by_dataset(results_b, results_b_naive, output_dir)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Visual VQA inference and evaluation on AgML datasets."
    )
    parser.add_argument(
        "--model", default="Qwen/Qwen3.6-35B-A3B",
        help="vLLM-compatible VLM (HuggingFace ID or local path)",
    )
    parser.add_argument(
        "--descriptions_jsonl", default="outputs/agml_descriptions.jsonl",
        help="Path to agml_descriptions.jsonl produced by agml_scraper.py",
    )
    parser.add_argument(
        "--datasets_config", default="datasets.yaml",
        help="Path to datasets.yaml registry (controls which datasets are evaluated)",
    )
    parser.add_argument(
        "--output_dir", default="inference_results/",
        help="Directory for CSV results, metrics JSON, and plots",
    )
    parser.add_argument(
        "--n_samples", type=int, default=None,
        help="Max images per class to evaluate (default: all from image_names)",
    )
    args = parser.parse_args()
    main(args)
