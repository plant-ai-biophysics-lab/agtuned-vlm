# ── LLM-as-a-judge ────────────────────────────────────────────────────────────

_JUDGE_PARAMS = SamplingParams(temperature=0.0, max_tokens=8)

_DESC_JUDGE_TMPL = (
    "Compare two visual plant condition descriptions.\n"
    "Reference: {gt}\n"
    "Prediction: {pred}\n"
    "Does the prediction capture the same key visual features (colors, patterns, "
    "lesions, textures, symptoms) as the reference? Answer YES or NO only."
)

_CLS_JUDGE_TMPL = (
    "Reference class: {gt}\n"
    "Prediction: {pred}\n"
    "Is the prediction referring to the same disease, pest, or plant condition? "
    "Answer YES or NO only."
)


def _apply_judge(rows: list[dict], mode: str, llm: LLM, tokenizer) -> list[dict]:
    """Apply judge LLM to rows; adds judged_correct (0/1) to each row."""
    if mode == "description":
        raw_prompts = [
            _DESC_JUDGE_TMPL.format(gt=r["ground_truth"][:400], pred=r["prediction"][:400])
            for r in rows
        ]
    else:
        raw_prompts = [
            _CLS_JUDGE_TMPL.format(
                gt=r["class_label"],
                pred=(r.get("resolved_class") or r.get("raw_prediction", ""))[:200],
            )
            for r in rows
        ]

    def _fmt(text: str) -> str:
        msgs = [{"role": "user", "content": text}]
        try:
            return tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        except Exception:
            return text

    outputs = llm.generate([_fmt(p) for p in raw_prompts], sampling_params=_JUDGE_PARAMS)
    return [
        {**row, "judged_correct": int(out.outputs[0].text.strip().upper().startswith("YES"))}
        for row, out in zip(rows, outputs)
    ]


def judged_summary(rows: list[dict]) -> dict:
    judged = [r for r in rows if "judged_correct" in r]
    if not judged:
        return {}
    return {
        "judge_accuracy": round(sum(r["judged_correct"] for r in judged) / len(judged), 4),
        "n_judged": len(judged),
    }


# ── Tee: mirror stdout to file ────────────────────────────────────────────────

class _Tee:
    """Write to both stdout and a file simultaneously."""
    def __init__(self, path: Path):
        self._file   = open(path, "w", encoding="utf-8")
        self._stdout = sys.stdout

    def write(self, data: str):
        self._stdout.write(data)
        self._file.write(data)

    def flush(self):
        self._stdout.flush()
        self._file.flush()

    def close(self):
        sys.stdout = self._stdout
        self._file.close()


# ── Main ───────────────────────────────────────────────────────────────────────

def main(args: argparse.Namespace) -> None:
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    datasets_cfg    = load_datasets_config(Path(args.datasets_config))
    active_datasets = set(datasets_cfg.keys())
    records         = load_description_records(
        Path(args.descriptions_jsonl), active_datasets
    )

    print(f"\nModel:   {args.model}")
    print(f"Records: {len(records)}  |  Datasets: {len(active_datasets)}")
    llm, tokenizer = load_llm(args.model)

    desc_rows: list[dict] = []
    cls_rows:  list[dict] = []
    agml_cache: dict[str, dict[str, str]] = {}  # agml_name → {filename: path}

    t_start = time.perf_counter()

    for record in records:
        meta          = record["metadata"]
        agml_name     = meta["agml_dataset"]
        class_label   = meta["class_label"]
        task_type     = meta["task_type"]
        crop          = meta["crop"]
        image_names   = meta["image_names"]
        synth_desc    = record["messages"][1]["content"]
        visual_desc_q = meta["visual_question"]
        visual_cls_q  = meta.get("visual_cls_question")

        if args.n_samples:
            image_names = image_names[:args.n_samples]

        # Build AgML filename→path map (cached per dataset)
        if agml_name not in agml_cache:
            print(f"\n  Building image map: {agml_name}...")
            agml_cache[agml_name] = build_name_map(agml_name)
        name_map = agml_cache[agml_name]

        images, valid_names = [], []
        for name in image_names:
            if name in name_map:
                images.append(PILImage.open(name_map[name]).convert("RGB"))
                valid_names.append(name)
            else:
                print(f"    [warn] {name} not in {agml_name}")
        if not images:
            continue

        print(f"  {agml_name} / {class_label}  ({len(images)} images)")

        # ── Dataset A: visual description ─────────────────────────────────
        desc_preds = run_batch(llm, tokenizer, images, visual_desc_q, DESC_PARAMS)
        for pred, img_name in zip(desc_preds, valid_names):
            scores = rouge_scores(pred, synth_desc)
            desc_rows.append({
                "agml_dataset": agml_name,
                "class_label":  class_label,
                "task_type":    task_type,
                "crop":         crop,
                "image_name":   img_name,
                "prediction":   pred,
                "ground_truth": synth_desc,
                **scores,
            })

        # ── Dataset B: visual classification ──────────────────────────────
        if visual_cls_q:
            raw_classes   = datasets_cfg[agml_name].get("classes", [])
            clean_classes = clean_class_list(raw_classes)
            cls_question  = visual_cls_q + CLS_SUFFIX

            cls_preds  = run_batch(llm, tokenizer, images, cls_question, CLS_PARAMS)
            resolved_list = [resolve_class(p, clean_classes) for p in cls_preds]
            bert_scores   = compute_bertscore(
                [r or p for r, p in zip(resolved_list, cls_preds)],
                [class_label] * len(cls_preds),
            )
            for pred, img_name, resolved, bs in zip(
                cls_preds, valid_names, resolved_list, bert_scores
            ):
                correct   = resolved is not None and resolved.lower() == class_label.lower()
                contains  = contains_match(resolved or pred, class_label)
                cls_rows.append({
                    "agml_dataset":   agml_name,
                    "class_label":    class_label,
                    "task_type":      task_type,
                    "crop":           crop,
                    "image_name":     img_name,
                    "raw_prediction": pred,
                    "resolved_class": resolved or "",
                    "correct":        int(correct),
                    "contains_match": int(contains),
                    "bertscore":      round(bs, 4),
                    "resolvable":     int(resolved is not None),
                })

    elapsed = time.perf_counter() - t_start

    # ── Free main model before loading judge ──────────────────────────────────
    del llm, tokenizer
    import gc; gc.collect()

    # ── LLM-as-a-judge (before CSV save so judged_correct col is included) ────
    if args.judge_model:
        print(f"\n=== LLM Judge: {args.judge_model} ===")
        judge_llm = LLM(
            model=args.judge_model, dtype="bfloat16",
            max_model_len=1024, gpu_memory_utilization=0.85,
        )
        judge_tok = judge_llm.get_tokenizer()
        if desc_rows:
            print(f"  Judging {len(desc_rows)} description rows...")
            desc_rows = _apply_judge(desc_rows, "description", judge_llm, judge_tok)
        if cls_rows:
            print(f"  Judging {len(cls_rows)} classification rows...")
            cls_rows = _apply_judge(cls_rows, "classification", judge_llm, judge_tok)
        del judge_llm, judge_tok
        gc.collect()

    # ── Save per-image CSVs ────────────────────────────────────────────────────
    if desc_rows:
        desc_csv = output_dir / "agml_inference_descriptions.csv"
        with open(desc_csv, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(desc_rows[0].keys()))
            writer.writeheader()
            writer.writerows(desc_rows)
        print(f"\nSaved: {desc_csv}")

    if cls_rows:
        cls_csv = output_dir / "agml_inference_classification.csv"
        with open(cls_csv, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(cls_rows[0].keys()))
            writer.writeheader()
            writer.writerows(cls_rows)
        print(f"Saved: {cls_csv}")

    # ── Aggregate metrics ──────────────────────────────────────────────────────
    by_ds_desc: dict[str, list] = defaultdict(list)
    for row in desc_rows:
        by_ds_desc[row["agml_dataset"]].append(row)

    by_ds_cls: dict[str, list] = defaultdict(list)
    for row in cls_rows:
        by_ds_cls[row["agml_dataset"]].append(row)

    ds_to_task = {name: cfg["task_type"] for name, cfg in datasets_cfg.items()}

    results_a       = {ds: dataset_rouge_summary(rows) for ds, rows in by_ds_desc.items()}
    results_a_naive = {ds: naive_rouge_summary(rows)   for ds, rows in by_ds_desc.items()}
    if desc_rows:
        results_a["overall"]       = dataset_rouge_summary(desc_rows)
        results_a_naive["overall"] = naive_rouge_summary(desc_rows)

    # Per-task ROUGE aggregation
    by_task_desc: dict[str, list] = defaultdict(list)
    for row in desc_rows:
        tt = ds_to_task.get(row["agml_dataset"])
        if tt:
            by_task_desc[tt].append(row)
    results_a_by_task       = {tt: dataset_rouge_summary(rows) for tt, rows in by_task_desc.items()}
    results_a_naive_by_task = {tt: naive_rouge_summary(rows)   for tt, rows in by_task_desc.items()}

    results_b       = {ds: dataset_cls_summary(rows) for ds, rows in by_ds_cls.items()}
    results_b_naive = {ds: naive_cls_summary(rows)   for ds, rows in by_ds_cls.items()}

    # Per-task classification aggregation
    by_task_cls:  dict[str, list] = defaultdict(list)
    for row in cls_rows:
        tt = ds_to_task.get(row["agml_dataset"])
        if tt:
            by_task_cls[tt].append(row)

    results_b_by_task       = {tt: dataset_cls_summary(rows) for tt, rows in by_task_cls.items()}
    results_b_naive_by_task = {tt: naive_cls_summary(rows)   for tt, rows in by_task_cls.items()}

    # Overall across all datasets
    if cls_rows:
        results_b["overall"]             = dataset_cls_summary(cls_rows)
        results_b_naive["overall"]       = naive_cls_summary(cls_rows)

    # ── Judged aggregation (only populated when --judge_model is set) ──────────
    results_a_judged         = {ds: judged_summary(rows) for ds, rows in by_ds_desc.items()}
    results_a_judged_by_task = {tt: judged_summary(rows) for tt, rows in by_task_desc.items()}
    if desc_rows:
        results_a_judged["overall"] = judged_summary(desc_rows)

    results_b_judged         = {ds: judged_summary(rows) for ds, rows in by_ds_cls.items()}
    results_b_judged_by_task = {tt: judged_summary(rows) for tt, rows in by_task_cls.items()}
    if cls_rows:
        results_b_judged["overall"] = judged_summary(cls_rows)

    results = {
        "model":                     args.model,
        "judge_model":               args.judge_model,
        "total_time_s":              round(elapsed, 3),
        "n_classes":                 len(records),
        "dataset_a":                 results_a,
        "dataset_a_naive":           results_a_naive,
        "dataset_a_by_task":         results_a_by_task,
        "dataset_a_naive_by_task":   results_a_naive_by_task,
        "dataset_a_judged":          results_a_judged,
        "dataset_a_judged_by_task":  results_a_judged_by_task,
        "dataset_b":                 results_b,
        "dataset_b_naive":           results_b_naive,
        "dataset_b_by_task":         results_b_by_task,
        "dataset_b_naive_by_task":   results_b_naive_by_task,
        "dataset_b_judged":          results_b_judged,
        "dataset_b_judged_by_task":  results_b_judged_by_task,
    }
    metrics_path = output_dir / "agml_inference_metrics.json"
    with open(metrics_path, "w") as f:
        json.dump(results, f, indent=2)
    print(f"Saved: {metrics_path}")

    # ── Summary (mirrored to summary.txt) ─────────────────────────────────────
    tee = _Tee(output_dir / "summary.txt")
    sys.stdout = tee
    try:
        if results_a:
            print(f"\n=== Dataset A — Visual Description ===")
            header = (f"  {'Dataset':<45} {'R-1':>6} {'R-2':>6} {'R-L':>6} {'R-SS':>6} "
                      f"{'N-R1':>7} {'N-R2':>7} {'N-RL':>7} {'N-SS':>7} {'N':>6}")
            print(header)
            print(f"  {'-' * len(header)}")
            for ds, m in results_a.items():
                if ds == "overall":
                    continue
                naive = results_a_naive.get(ds, {})
                print(f"  {ds:<45} {m['rouge1']:>6.3f} {m['rouge2']:>6.3f} "
                      f"{m['rougeL']:>6.3f} {m['rouge_ss']:>6.3f} "
                      f"{naive.get('rouge1', 0):>7.3f} {naive.get('rouge2', 0):>7.3f} "
                      f"{naive.get('rougeL', 0):>7.3f} {naive.get('rouge_ss', 0):>7.3f} "
                      f"{m['n_images']:>6}")
            if results_a_by_task:
                print(f"\n  {'Task':<25} {'R-1':>6} {'R-2':>6} {'R-L':>6} {'R-SS':>6} "
                      f"{'N-R1':>7} {'N-R2':>7} {'N-RL':>7} {'N-SS':>7}")
                print(f"  {'-'*80}")
                for tt, m in sorted(results_a_by_task.items()):
                    naive = results_a_naive_by_task.get(tt, {})
                    print(f"  {_task_label(tt):<25} {m['rouge1']:>6.3f} {m['rouge2']:>6.3f} "
                          f"{m['rougeL']:>6.3f} {m['rouge_ss']:>6.3f} "
                          f"{naive.get('rouge1', 0):>7.3f} {naive.get('rouge2', 0):>7.3f} "
                          f"{naive.get('rougeL', 0):>7.3f} {naive.get('rouge_ss', 0):>7.3f}")
            if "overall" in results_a:
                ov    = results_a["overall"]
                naive = results_a_naive.get("overall", {})
                print(f"\n  {'OVERALL':<25} {ov['rouge1']:>6.3f} {ov['rouge2']:>6.3f} "
                      f"{ov['rougeL']:>6.3f} {ov['rouge_ss']:>6.3f} "
                      f"{naive.get('rouge1', 0):>7.3f} {naive.get('rouge2', 0):>7.3f} "
                      f"{naive.get('rougeL', 0):>7.3f} {naive.get('rouge_ss', 0):>7.3f} "
                      f"({ov['n_images']} images)")

        if results_b:
            print(f"\n=== Dataset B — Visual Classification ===")
            header = (f"  {'Dataset':<45} {'Acc':>6} {'Cont':>6} {'F1-mac':>8} "
                      f"{'BERT':>6} {'N-Acc':>7} {'N-BERT':>7} {'Res/Tot':>9}")
            print(header)
            print(f"  {'-' * len(header)}")
            for ds, m in results_b.items():
                if ds == "overall":
                    continue
                naive = results_b_naive.get(ds, {})
                print(f"  {ds:<45} {m['accuracy']:>6.3f} {m['contains_accuracy']:>6.3f} "
                      f"{m['f1_macro']:>8.3f} {m['mean_bertscore']:>6.3f} "
                      f"{naive.get('accuracy', 0):>7.3f} {naive.get('mean_bertscore', 0):>7.3f} "
                      f"{m['n_resolvable']:>4}/{m['n_images']:<4}")
            if "overall" in results_b:
                ov = results_b["overall"]
                nv = results_b_naive.get("overall", {})
                print(f"\n  {'OVERALL':<45} {ov['accuracy']:>6.3f} {ov['contains_accuracy']:>6.3f} "
                      f"{ov['f1_macro']:>8.3f} {ov['mean_bertscore']:>6.3f} "
                      f"{nv.get('accuracy', 0):>7.3f} {nv.get('mean_bertscore', 0):>7.3f} "
                      f"{ov['n_resolvable']:>4}/{ov['n_images']:<4}")

        if results_b_by_task:
            print(f"\n=== Dataset B — By Task Type ===")
            header = (f"  {'Task':<25} {'Acc':>6} {'Cont':>6} {'F1-mac':>8} "
                      f"{'BERT':>6} {'N-Acc':>7} {'N-BERT':>7}")
            print(header)
            print(f"  {'-' * len(header)}")
            for tt, m in results_b_by_task.items():
                naive = results_b_naive_by_task.get(tt, {})
                print(f"  {_task_label(tt):<25} {m['accuracy']:>6.3f} {m['contains_accuracy']:>6.3f} "
                      f"{m['f1_macro']:>8.3f} {m['mean_bertscore']:>6.3f} "
                      f"{naive.get('accuracy', 0):>7.3f} {naive.get('mean_bertscore', 0):>7.3f}")

        # ── LLM Judge summary (only when --judge_model was set) ───────────────
        if args.judge_model and (any(results_a_judged.values()) or any(results_b_judged.values())):
            print(f"\n=== LLM Judge Results [judged] — {args.judge_model} ===")
            if results_a_judged:
                print(f"\n  Dataset A — Description Judge Accuracy")
                print(f"  {'Dataset':<45} {'J-Acc':>7} {'N':>6}")
                print(f"  {'-'*62}")
                for ds, jm in results_a_judged.items():
                    if ds == "overall" or not jm:
                        continue
                    print(f"  {ds:<45} {jm['judge_accuracy']:>7.3f} {jm['n_judged']:>6}")
                if results_a_judged_by_task:
                    print(f"\n  {'Task':<25} {'J-Acc':>7}")
                    print(f"  {'-'*34}")
                    for tt, jm in sorted(results_a_judged_by_task.items()):
                        if jm:
                            print(f"  {_task_label(tt):<25} {jm['judge_accuracy']:>7.3f}")
                ov = results_a_judged.get("overall", {})
                if ov:
                    print(f"\n  {'OVERALL':<45} {ov['judge_accuracy']:>7.3f} {ov['n_judged']:>6}")

            if results_b_judged:
                print(f"\n  Dataset B — Classification Judge Accuracy")
                print(f"  {'Dataset':<45} {'J-Acc':>7} {'N':>6}")
                print(f"  {'-'*62}")
                for ds, jm in results_b_judged.items():
                    if ds == "overall" or not jm:
                        continue
                    print(f"  {ds:<45} {jm['judge_accuracy']:>7.3f} {jm['n_judged']:>6}")
                if results_b_judged_by_task:
                    print(f"\n  {'Task':<25} {'J-Acc':>7}")
                    print(f"  {'-'*34}")
                    for tt, jm in sorted(results_b_judged_by_task.items()):
                        if jm:
                            print(f"  {_task_label(tt):<25} {jm['judge_accuracy']:>7.3f}")
                ov = results_b_judged.get("overall", {})
                if ov:
                    print(f"\n  {'OVERALL':<45} {ov['judge_accuracy']:>7.3f} {ov['n_judged']:>6}")

        print(f"\nTotal time: {elapsed:.1f}s")
        print(f"Model:      {args.model}")

        # ── Plots ──────────────────────────────────────────────────────────────
        print("\nGenerating plots...")
        results_a_plot       = {k: v for k, v in results_a.items()       if k != "overall"}
        results_a_naive_plot = {k: v for k, v in results_a_naive.items() if k != "overall"}
        plot_rouge_by_dataset(results_a_plot, results_a_naive_plot, output_dir)
        plot_rouge_by_task(results_a_by_task, results_a_naive_by_task, output_dir)
        results_b_plot       = {k: v for k, v in results_b.items()       if k != "overall"}
        results_b_naive_plot = {k: v for k, v in results_b_naive.items() if k != "overall"}
        plot_cls_by_dataset(results_b_plot, results_b_naive_plot, output_dir)
        plot_cls_by_task(results_b_by_task, results_b_naive_by_task, output_dir)
    finally:
        tee.close()
    print(f"Summary saved to {output_dir / 'summary.txt'}")


